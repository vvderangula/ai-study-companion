def test_tutor_grounded_and_unsupported(client, auth, ready_project, fresh_db):
    pid = ready_project["project"]["id"]
    r = client.post(f"/projects/{pid}/tutor/ask/sync", json={"message": "What is photosynthesis and what does chlorophyll do?"}, headers=auth)
