def test_eval_run_and_regression_compare(client, auth, ready_project):
    from tests.conftest import register

    admin = register(client, "admin@example.com")
    pid = ready_project["project"]["id"]
    r = client.post("/admin/evals", json={"project_id": pid}, headers=admin)
    assert r.status_code == 201, r.text
    run = r.json()["run"]
    assert run["status"] == "completed" and run["total_cases"] >= 7
    assert run["scores"]["category:tutor_unsupported"] >= 0.7
    assert run["scores"]["category:safety"] >= 0.7
    assert run["prompt_versions"]["tutor"]
    r2 = client.post("/admin/evals", json={"project_id": pid}, headers=admin).json()["run"]
    assert r2["baseline_run_id"] == run["id"]
    assert client.get("/admin/evals", headers=admin).json()[0]["id"] == r2["id"]
    assert len(client.get(f"/admin/evals/{r2['id']}", headers=admin).json()["results"]) == r2["total_cases"]
