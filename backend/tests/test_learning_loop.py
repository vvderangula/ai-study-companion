def test_quiz_adaptive_loop_updates_mastery_and_recommends(client, auth, ready_project):
    pid = ready_project["project"]["id"]
    r = client.post(f"/projects/{pid}/quiz/sessions", json={"question_count": 3}, headers=auth)
    assert r.status_code == 201, r.text
    session = r.json()["session"]
    q = r.json()["question"]
    assert q["kind"] == "mcq" and len(q["options"]) == 4 and "correct_option" not in q
    sid = session["id"]

    # answer wrong
    wrong = 1
    a1 = client.post(f"/projects/{pid}/quiz/sessions/{sid}/answer", json={"question_id": q["id"], "answer": str(wrong)}, headers=auth).json()
    assert a1["is_correct"] is False and a1["correct_option"] == 0 and "Not quite" in a1["feedback"]
    assert a1["mastery"]["score"] < 0.3 and a1["mastery"]["attempts"] == 1
    # answering twice is rejected
    dup = client.post(f"/projects/{pid}/quiz/sessions/{sid}/answer", json={"question_id": q["id"], "answer": "0"}, headers=auth)
    assert dup.status_code == 409

    q2 = a1["next_question"]
    assert q2 is not None and q2["ordinal"] == 1
    a2 = client.post(f"/projects/{pid}/quiz/sessions/{sid}/answer", json={"question_id": q2["id"], "answer": "0" if q2["kind"] == "mcq" else "It happens in the stroma and makes glucose."}, headers=auth).json()
    assert a2["is_correct"] is True

    q3 = a2["next_question"]
    assert q3 is not None
    assert q3["kind"] == "open"  # at least one open question per quiz (ordinal 2 of 3)
    a3 = client.post(f"/projects/{pid}/quiz/sessions/{sid}/answer", json={"question_id": q3["id"], "answer": "It is in the stroma and produces glucose."}, headers=auth).json()
    assert a3["completed"] is True and a3["session"]["status"] == "completed"
    assert a3["evaluation"]["covered_points"] == ["stroma"] and a3["feedback"]
    assert a3["next_question"] is None

    # growth + recommendation (post_quiz workflow ran inline)
    growth = client.get(f"/projects/{pid}/growth", headers=auth).json()
    assert growth["overall_mastery"] > 0
    assert len(growth["history"]) == 3
    assert growth["recommendation"]["trigger"] == "quiz_completed"
    recs = client.get(f"/projects/{pid}/recommendations", headers=auth).json()
    assert recs[0]["status"] == "active" and any(r["status"] == "superseded" for r in recs)

    dash = client.get(f"/projects/{pid}", headers=auth).json()
    assert dash["progress"]["concepts_assessed"] >= 1
    assert dash["continue_learning"]["tab"] in ("growth", "quiz")

    analytics = client.get(f"/projects/{pid}/analytics", headers=auth).json()
    assert analytics["activity"]["questions_answered"] == 3
    assert analytics["performance"]["quiz_accuracy"] is not None
    assert analytics["ai_activity"]["quiz_questions_generated"] >= 3

    g = client.get("/analytics", headers=auth).json()
    assert g["overall"]["projects"] == 1 and g["performance"]["average_assessment"] is not None
    home = client.get("/home", headers=auth).json()
    assert home["continue_learning"]["project"]["id"] == pid


