    reqs = list(dbm.get_db()[dbm.AI_REQUESTS].find({"feature": "tutor"}))
    assert len(reqs) == 2 and reqs[0]["retrieval"]["hits"]
    # learner-context distillation ran for the grounded exchange
    assert dbm.get_db()[dbm.LEARNER_NOTES].count_documents({"project_id": pid, "kind": "preference"}) == 1


